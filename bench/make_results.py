#!/usr/bin/env python3
# make_results.py - turns results/detection.csv and results/overhead.csv into results/RESULTS.md.
# Called by run_bench.sh; can be re-run alone. Usage: make_results.py TSAN_OK HELGRIND_OK RUNS
import csv, statistics, sys, platform, subprocess, collections
tsan_ok, hg_ok, runs = sys.argv[1] == "1", sys.argv[2] == "1", sys.argv[3]
det = list(csv.DictReader(open("results/detection.csv")))
ov = list(csv.DictReader(open("results/overhead.csv")))
tools = [t for t in ["lockspy", "naive", "tsan", "helgrind"] if any(r["tool"] == t for r in det)]
label = {"lockspy": "LockSpy", "naive": "LockSpy --naive", "tsan": "ThreadSanitizer", "helgrind": "Helgrind", "bare": "bare"}
def sh(c):
    try: return subprocess.run(c, shell=True, capture_output=True, text=True).stdout.strip()
    except Exception: return "?"
out = []
w = out.append
w("# LockSpy evaluation results\n")
w("Generated by `bench/run_bench.sh`. Every number below comes from that run; nothing is hand-edited.\n")
w(f"- Machine: {sh('nproc')} CPUs, {platform.machine()}, kernel {platform.release()}")
w(f"- OS: {sh('. /etc/os-release && echo $PRETTY_NAME')}; compiler: {sh('g++ --version | head -1')}")
w(f"- Valgrind: {sh('valgrind --version') or 'not installed'}; ThreadSanitizer: {'GCC -fsanitize=thread' if tsan_ok else 'not available'}")
w(f"- Overhead: median of {runs} runs (Helgrind: 1 run), wall-clock time of the whole process.\n")
w("## Detection per test program\n")
w("`caught` = a buggy program got at least one finding of the expected type; `missed` = it did not; "
  "`clean` = a correct/tricky program got no warning; `false alarm` = it got one.\n")
progs = []
for r in det:
    k = (r["program"], r["args"])
    if k not in progs: progs.append(k)
w("| program | expected | " + " | ".join(label[t] for t in tools) + " |")
w("|---|---|" + "---|" * len(tools))
cell = {(r["program"], r["args"], r["tool"]): r for r in det}
for p, a in progs:
    exp = cell[(p, a, tools[0])]["expected"].replace(";", ", ")
    row = []
    for t in tools:
        r = cell[(p, a, t)]
        rep = r["reported"].replace(";", ", ")
        row.append(f"{r['verdict']} ({rep})" if r["reported"] != "NONE" else r["verdict"])
    w(f"| {p} {a} | {exp} | " + " | ".join(row) + " |")
w("\n## Precision and recall (program level)\n")
w("Positives: the buggy programs. Negatives: the correct and tricky programs. "
  "precision = caught / (caught + false alarms), recall = caught / buggy programs.\n")
w("| tool | caught | missed | false alarms | clean | precision | recall | exact finding types* | recompile needed |")
w("|---|---|---|---|---|---|---|---|---|")
summary = {}
for t in tools:
    rs = [r for r in det if r["tool"] == t]
    c = collections.Counter(r["verdict"] for r in rs)
    tp, fn, fp, tn = c["caught"], c["missed"], c["false alarm"], c["clean"]
    prec = tp / (tp + fp) if tp + fp else 0
    rec = tp / (tp + fn) if tp + fn else 0
    exact = sum(1 for r in rs if sorted(set(r["reported"].split(";"))) == sorted(set(r["expected"].split(";"))))
    summary[t] = (tp, fn, fp, tn, prec, rec, exact, len(rs))
    w(f"| {label[t]} | {tp} | {fn} | {fp} | {tn} | {prec:.2f} | {rec:.2f} | {exact}/{len(rs)} | {'yes' if t == 'tsan' else 'no'} |")
w("\n\\* exact = the set of finding types equals the expected set (LockSpy's own vocabulary; other tools "
  "do not report live deadlocks or held-at-exit the same way, so this column favours LockSpy by design).\n")
w("## Run-time overhead\n")
times = collections.defaultdict(list)
for r in ov: times[(r["program"], r["tool"])].append(float(r["seconds"]))
otools = [t for t in ["bare", "lockspy", "tsan", "helgrind"] if any(k[1] == t for k in times)]
w("| program | " + " | ".join(label[t] + (" (s)" if t == "bare" else "") for t in otools) + " |")
w("|---|" + "---|" * len(otools))
slow = collections.defaultdict(list)
for p in dict.fromkeys(k[0] for k in times):
    base = statistics.median(times[(p, "bare")])
    row = []
    for t in otools:
        m = statistics.median(times[(p, t)])
        if t == "bare": row.append(f"{m:.3f}")
        else:
            row.append(f"{m:.3f} s ({m / base:.1f}x)")
            slow[t].append(m / base)
    w(f"| {p} | " + " | ".join(row) + " |")
w("")
for t in otools[1:]:
    g = statistics.geometric_mean(slow[t])
    w(f"- {label[t]}: geometric-mean slowdown **{g:.1f}x** over these {len(slow[t])} programs.")
p = "perf/uncontended_loop 1000000"
if (p, "lockspy") in times:
    pairs = 4 * 1000000
    d = statistics.median(times[(p, "lockspy")]) - statistics.median(times[(p, "bare")])
    w(f"- Uncontended lock+unlock pair: about **{d / pairs * 1e9:.0f} ns** extra per pair under LockSpy "
      f"({pairs} pairs, 4 threads, each on its own mutex).")
w("\n## Reading these numbers honestly\n")
w("- The test programs are small and were written for this project; they show the detector works as designed, "
  "they are not a sample of real-world bugs.")
w("- ThreadSanitizer is mainly a data-race detector (its deadlock detector is a side feature) and needs a recompile. "
  "Helgrind needs no recompile but runs the program on a simulated CPU.")
faster = [p for p in dict.fromkeys(k[0] for k in times) if (p, "tsan") in times and
          statistics.median(times[(p, "tsan")]) < statistics.median(times[(p, "lockspy")])]
if faster:
    w("- **ThreadSanitizer was faster than LockSpy on: " + ", ".join(f"`{p.strip()}`" for p in faster) + ".** "
      "LockSpy serialises every lock event of every thread on one private lock, so a tight lock/unlock loop in several "
      "threads pays for that; TSan keeps per-thread state.")
w("- Most correct/ programs run for a few milliseconds, so their slowdown factors are dominated by start-up cost "
  "(loading the library, starting the watchdog) rather than per-lock cost.")
w("- For the programs that really hang (`--hang`, `philosophers_naive`, `recursive_lock`), ThreadSanitizer and Helgrind "
  "were killed by the timeout; only what they printed before that counts. LockSpy's watchdog reported and aborted.")
w("- ThreadSanitizer was run under `setarch -R` (ASLR off), which GCC 13's TSan needs on this kernel.")
w("- LockSpy's selling points are that it needs no recompile, separates *potential* from *live* deadlocks, "
  "filters gate-lock / single-thread / trylock patterns, and prints a concrete lock order as the fix.")
open("results/RESULTS.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
